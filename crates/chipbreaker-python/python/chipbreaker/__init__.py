"""Material-removal simulation and machining verification.

The engine computes what a program will leave behind and compares it against
the part you meant to make. It reports findings with the error budget that
makes them evidence rather than assertion, and it declines jobs it cannot
answer for -- by name, with a reason.

    >>> import chipbreaker
    >>> report = chipbreaker.verify(
    ...     program="part.nc", tools="library.json", stock="stock.stl",
    ...     nominal="part.stl",
    ... )
    >>> report["verdict"]["pass"]
    False
    >>> report["verdict"]["gates"]["gouge"]
    {'state': 'fail', 'why': '2 gouges above tolerance'}

A declined job raises `Refused`, and the message is the engine's own sentence:

    >>> try:
    ...     chipbreaker.verify(program="siemens.mpf", tools=..., stock=...)
    ... except chipbreaker.Refused as e:
    ...     print(e)
    line 5: this looks like Siemens 840D, which is a different language rather
    than a dialect of RS-274 (found "DEF REAL")

**A refusal is an answer, not a failure.** Show the message and stop. Retrying
will produce the same one, because nothing about the input has changed.

**An unchecked gate does not pass.** Running without a nominal does not give
you a clean part; it gives you a report saying the gouge gate never ran.
`report["verdict"]["pass"]` is False, correctly, and the gate says why.
"""

